/**
 * Reusable standalone AudioPlayer component in Compose.
 *
 * Automatically manages MediaPlayer lifecycle, extracts visual waveform amplitudes
 * from .wav files generated by Gemini API, and provides controls for:
 * - Play / Pause
 * - Scrubbing (waveform tap/drag & slider)
 * - 5s rewind / 5s fast forward
 * - Variable playback speed (0.8x, 1.0x, 1.25x, 1.5x)
 * - Loop mode toggle
 * - Formatted timestamps
 */
@Composable
fun AudioPlayer(
    audioFile: File,
    modifier: Modifier = Modifier,
    title: String? = "Generated Narration Audio",
    subtitle: String? = null,
    autoPlay: Boolean = false,
    onShareClick: (() -> Unit)? = null
) {
    var isPlaying by remember { mutableStateOf(false) }
    var currentPositionMs by remember { mutableIntStateOf(0) }
    var durationMs by remember { mutableIntStateOf(0) }
    var playbackSpeed by remember { mutableFloatStateOf(1.0f) }
    var isLooping by remember { mutableStateOf(false) }
    var amplitudes by remember(audioFile) {
        mutableStateOf(
            if (audioFile.exists() && audioFile.length() > 0) {
                try {
                    WavAudioUtil.extractAmplitudes(audioFile.readBytes(), barCount = 44)
                } catch (e: Exception) {
                    emptyList()
                }
            } else {
                emptyList()
            }
        )
    }

    val mediaPlayer = remember(audioFile) { MediaPlayer() }

    DisposableEffect(audioFile) {
        try {
            mediaPlayer.reset()
            mediaPlayer.setDataSource(audioFile.absolutePath)
            mediaPlayer.setOnPreparedListener { mp ->
                durationMs = mp.duration.coerceAtLeast(0)
                currentPositionMs = 0
                mp.isLooping = isLooping
                if (autoPlay) {
                    mp.start()
                    isPlaying = true
                }
            }
            mediaPlayer.setOnCompletionListener {
                if (!isLooping) {
                    isPlaying = false
                    currentPositionMs = durationMs
                }
            }
            mediaPlayer.setOnErrorListener { _, _, _ ->
                isPlaying = false
                true
            }
            mediaPlayer.prepareAsync()
        } catch (e: Exception) {
            // handle setup failure gracefully
        }

        onDispose {
            try {
                if (mediaPlayer.isPlaying) {
                    mediaPlayer.stop()
                }
                mediaPlayer.release()
            } catch (e: Exception) {
                // ignore release errors
            }
        }
    }

    // Progress polling loop
    LaunchedEffect(isPlaying) {
        while (isActive && isPlaying) {
            try {
                currentPositionMs = mediaPlayer.currentPosition
            } catch (e: Exception) {
                // ignore transient errors
            }
            delay(60)
        }
    }

    val progress = if (durationMs > 0) {
        (currentPositionMs.toFloat() / durationMs).coerceIn(0f, 1f)
    } else {
        0f
    }

    AudioPlayer(
        isPlaying = isPlaying,
        progress = progress,
        currentPositionMs = currentPositionMs,
        durationMs = durationMs,
        amplitudes = amplitudes,
        playbackSpeed = playbackSpeed,
        isLooping = isLooping,
        title = title,
        subtitle = subtitle,
        modifier = modifier,
        onTogglePlayPause = {
            if (isPlaying) {
                try {
                    mediaPlayer.pause()
                    isPlaying = false
                } catch (e: Exception) { }
            } else {
                try {
                    if (progress >= 0.99f) {
                        mediaPlayer.seekTo(0)
                        currentPositionMs = 0
                    }
                    mediaPlayer.start()
                    isPlaying = true
                } catch (e: Exception) { }
            }
        },
        onSeek = { fraction ->
            val targetMs = (fraction.coerceIn(0f, 1f) * durationMs).toInt()
            try {
                mediaPlayer.seekTo(targetMs)
                currentPositionMs = targetMs
            } catch (e: Exception) { }
        },
        onSpeedChange = { speed ->
            playbackSpeed = speed
            try {
                if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.M) {
                    val wasPlaying = try { mediaPlayer.isPlaying } catch (e: Exception) { false }
                    val params = mediaPlayer.playbackParams ?: PlaybackParams()
                    params.speed = speed
                    mediaPlayer.playbackParams = params
                    if (!wasPlaying) {
                        try { mediaPlayer.pause() } catch (e: Exception) { }
                    }
                }
            } catch (e: Exception) { }
        },
        onToggleLoop = {
            isLooping = !isLooping
            try {
                mediaPlayer.isLooping = isLooping
            } catch (e: Exception) { }
        },
        onShareClick = onShareClick
    )
}

/**
 * Controlled overload of the reusable AudioPlayer component.
 * Allows external state management (e.g. ViewModel or custom audio controllers).
 */
@Composable
fun AudioPlayer(
    isPlaying: Boolean,
    progress: Float,
    currentPositionMs: Int,
    durationMs: Int,
    amplitudes: List<Float>,
    onTogglePlayPause: () -> Unit,
    onSeek: (Float) -> Unit,
    modifier: Modifier = Modifier,
    playbackSpeed: Float = 1.0f,
    onSpeedChange: ((Float) -> Unit)? = null,
    isLooping: Boolean = false,
    onToggleLoop: (() -> Unit)? = null,
    title: String? = null,
    subtitle: String? = null,
    onShareClick: (() -> Unit)? = null
) {
    Card(
        modifier = modifier
            .fillMaxWidth()
            .testTag("reusable_audio_player"),
        shape = RoundedCornerShape(16.dp),
        colors = CardDefaults.cardColors(containerColor = StudioCardBg),
        border = BorderStroke(1.dp, StudioBorder)
    ) {
        Column(modifier = Modifier.padding(16.dp)) {
            // Header: Title & Optional Share Button
            Row(
                modifier = Modifier.fillMaxWidth(),
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.SpaceBetween
            ) {
                Row(
                    verticalAlignment = Alignment.CenterVertically,
                    modifier = Modifier.weight(1f, fill = false)
                ) {
                    Box(
                        modifier = Modifier
                            .size(32.dp)
                            .clip(CircleShape)
                            .background(GoldContainer),
                        contentAlignment = Alignment.Center
                    ) {
                        Icon(
                            imageVector = Icons.Default.GraphicEq,
                            contentDescription = null,
                            tint = GoldAmber,
                            modifier = Modifier.size(18.dp)
                        )
                    }
                    Spacer(modifier = Modifier.width(10.dp))
                    Column {
                        Text(
                            text = title ?: "AUDIO PLAYBACK",
                            style = MaterialTheme.typography.titleSmall.copy(fontWeight = FontWeight.Bold),
                            color = TextPrimary
                        )
                        if (subtitle != null) {
                            Text(
                                text = subtitle,
                                style = MaterialTheme.typography.bodySmall,
                                color = TextSecondary
                            )
                        }
                    }
                }

                if (onShareClick != null) {
                    IconButton(
                        onClick = onShareClick,
                        modifier = Modifier.testTag("audio_player_share_btn")
                    ) {
                        Icon(
                            imageVector = Icons.Default.Share,
                            contentDescription = "Share Audio",
                            tint = CyanAccent
                        )
                    }
                }
            }

            Spacer(modifier = Modifier.height(14.dp))

            // Interactive Waveform
            WaveformDisplay(
                amplitudes = amplitudes,
                progress = progress,
                isPlaying = isPlaying,
                onSeek = onSeek
            )

            // Scrubbing Slider
            Slider(
                value = progress,
                onValueChange = onSeek,
                modifier = Modifier
                    .fillMaxWidth()
                    .height(28.dp)
                    .testTag("audio_player_slider"),
                colors = SliderDefaults.colors(
                    thumbColor = GoldAmber,
                    activeTrackColor = GoldAmber,
                    inactiveTrackColor = StudioBorder
                )
            )

            // Timestamps
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween
            ) {
                Text(
                    text = formatPlaybackTime(currentPositionMs),
                    style = MaterialTheme.typography.labelSmall.copy(fontWeight = FontWeight.SemiBold),
                    color = GoldAmber
                )
                Text(
                    text = formatPlaybackTime(durationMs),
                    style = MaterialTheme.typography.labelSmall,
                    color = TextSecondary
                )
            }

            Spacer(modifier = Modifier.height(12.dp))

            // Controls: Loop, Rewind, Play/Pause, Forward, Speed
            Row(
                modifier = Modifier.fillMaxWidth(),
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.SpaceBetween
            ) {
                // Loop toggle
                if (onToggleLoop != null) {
                    IconButton(
                        onClick = onToggleLoop,
                        modifier = Modifier.testTag("audio_player_loop_btn")
                    ) {
                        Icon(
                            imageVector = if (isLooping) Icons.Default.RepeatOn else Icons.Default.Repeat,
                            contentDescription = "Loop Playback",
                            tint = if (isLooping) GoldAmber else TextSecondary
                        )
                    }
                } else {
                    Spacer(modifier = Modifier.width(36.dp))
                }

                // 5s Rewind
                IconButton(
                    onClick = {
                        val newMs = (currentPositionMs - 5000).coerceAtLeast(0)
                        val frac = if (durationMs > 0) newMs.toFloat() / durationMs else 0f
                        onSeek(frac)
                    }
                ) {
                    Icon(
                        imageVector = Icons.Default.FastRewind,
                        contentDescription = "Rewind 5s",
                        tint = TextPrimary
                    )
                }

                // Primary Play / Pause Button
                FilledIconButton(
                    onClick = onTogglePlayPause,
                    modifier = Modifier
                        .size(54.dp)
                        .testTag("audio_player_play_pause_btn"),
                    colors = IconButtonDefaults.filledIconButtonColors(
                        containerColor = GoldAmber,
                        contentColor = Color(0xFF1E1202)
                    )
                ) {
                    Icon(
                        imageVector = if (isPlaying) Icons.Default.Pause else Icons.Default.PlayArrow,
                        contentDescription = if (isPlaying) "Pause" else "Play",
                        modifier = Modifier.size(28.dp)
                    )
                }

                // 5s Forward
                IconButton(
                    onClick = {
                        val newMs = (currentPositionMs + 5000).coerceAtMost(durationMs)
                        val frac = if (durationMs > 0) newMs.toFloat() / durationMs else 0f
                        onSeek(frac)
                    }
                ) {
                    Icon(
                        imageVector = Icons.Default.FastForward,
                        contentDescription = "Forward 5s",
                        tint = TextPrimary
                    )
                }

                // Speed Selectors
                if (onSpeedChange != null) {
                    Row(horizontalArrangement = Arrangement.spacedBy(4.dp)) {
                        listOf(0.8f, 1.0f, 1.25f, 1.5f).forEach { speed ->
                            val isSelected = playbackSpeed == speed
                            Surface(
                                onClick = { onSpeedChange(speed) },
                                shape = RoundedCornerShape(6.dp),
                                color = if (isSelected) GoldAmber else StudioSurfaceVariant,
                                border = BorderStroke(1.dp, if (isSelected) GoldAmber else StudioBorder)
                            ) {
                                Text(
                                    text = "${speed}x",
                                    style = MaterialTheme.typography.labelSmall.copy(
                                        fontSize = 10.sp,
                                        fontWeight = FontWeight.Bold
                                    ),
                                    color = if (isSelected) Color(0xFF1E1202) else TextSecondary,
                                    modifier = Modifier.padding(horizontal = 6.dp, vertical = 4.dp)
                                )
                            }
                        }
                    }
                } else {
                    Spacer(modifier = Modifier.width(36.dp))
                }
            }
        }
    }
}

@Composable
private fun WaveformDisplay(
    amplitudes: List<Float>,
    progress: Float,
    isPlaying: Boolean,
    onSeek: (Float) -> Unit,
    modifier: Modifier = Modifier
) {
    val infiniteTransition = rememberInfiniteTransition(label = "player_waveform")
    val wavePhase by infiniteTransition.animateFloat(
        initialValue = 0f,
        targetValue = (2 * Math.PI).toFloat(),
        animationSpec = infiniteRepeatable(
            animation = tween(durationMillis = 1600, easing = FastOutSlowInEasing),
            repeatMode = RepeatMode.Restart
        ),
        label = "phase"
    )

    val displayAmplitudes = if (amplitudes.isNotEmpty()) {
        amplitudes
    } else {
        rememberDefaultAmplitudes()
    }

    Box(
        modifier = modifier
            .fillMaxWidth()
            .height(68.dp)
            .clip(RoundedCornerShape(10.dp))
            .background(StudioDarkBg)
            .pointerInput(Unit) {
                detectTapGestures { offset ->
                    val fraction = (offset.x / size.width).coerceIn(0f, 1f)
                    onSeek(fraction)
                }
            }
            .pointerInput(Unit) {
                detectHorizontalDragGestures { change, _ ->
                    val fraction = (change.position.x / size.width).coerceIn(0f, 1f)
                    onSeek(fraction)
                    change.consume()
                }
            }
    ) {
        Canvas(modifier = Modifier.matchParentSize()) {
            val width = size.width
            val height = size.height
            val barCount = displayAmplitudes.size
            if (barCount == 0) return@Canvas

            val spacingRatio = 0.22f
            val totalSpacing = width * spacingRatio
            val spacing = totalSpacing / (barCount + 1)
            val barWidth = (width - totalSpacing) / barCount

            for (i in 0 until barCount) {
                val baseAmp = displayAmplitudes[i]
                val oscillation = if (isPlaying) {
                    sin(wavePhase + (i * 0.4f)) * 0.2f
                } else {
                    0f
                }
                val dynamicAmp = (baseAmp * (1f + oscillation)).coerceIn(0.12f, 1.0f)
                val barHeight = (height * dynamicAmp).coerceIn(6.dp.toPx(), height * 0.90f)

                val x = spacing + i * (barWidth + spacing)
                val y = (height - barHeight) / 2f

                val barFraction = i.toFloat() / barCount
                val isPlayed = barFraction <= progress

                val color = when {
                    isPlayed -> GoldAmber
                    barFraction <= progress + 0.04f && isPlaying -> CyanAccent
                    else -> StudioBorder
                }

                drawRoundRect(
                    color = color,
                    topLeft = Offset(x, y),
                    size = Size(barWidth, barHeight),
                    cornerRadius = CornerRadius(barWidth / 2f, barWidth / 2f)
                )
            }

            // Scrub cursor
            val cursorX = width * progress.coerceIn(0f, 1f)
            drawLine(
                color = GoldAmber,
                start = Offset(cursorX, 0f),
                end = Offset(cursorX, height),
                strokeWidth = 2.dp.toPx()
            )
        }
    }
}

private fun rememberDefaultAmplitudes(): List<Float> {
    return listOf(
        0.30f, 0.45f, 0.60f, 0.80f, 0.95f, 0.75f, 0.50f, 0.35f, 0.65f, 0.85f,
        0.70f, 0.40f, 0.55f, 0.75f, 0.90f, 0.85f, 0.60f, 0.38f, 0.50f, 0.80f,
        0.92f, 0.88f, 0.65f, 0.42f, 0.30f, 0.58f, 0.82f, 0.74f, 0.50f, 0.35f,
        0.62f, 0.88f, 0.80f, 0.55f, 0.38f, 0.48f, 0.72f, 0.86f, 0.60f, 0.35f
    )
}

private fun formatPlaybackTime(millis: Int): String {
    val totalSeconds = (millis / 1000).coerceAtLeast(0)
    val minutes = totalSeconds / 60
    val seconds = totalSeconds % 60
    return String.format(Locale.US, "%02d:%02d", minutes, seconds)
}
